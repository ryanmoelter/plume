#!/usr/bin/env bash
# Regenerates the Swift gRPC client for the Android emulator controller proto.
# Usage: generate-emulator-grpc.sh [--update-proto] [--check]
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
PKG="$ROOT/Packages/EmulatorControl"
PROTO_DIR="$PKG/Protos"
PROTO="$PROTO_DIR/emulator_controller.proto"
OUT="$PKG/Sources/EmulatorControl/Generated"

update_proto=0
check=0
for arg in "$@"; do
  case "$arg" in
    --update-proto) update_proto=1 ;;
    --check) check=1 ;;
    *) echo "unknown option: $arg" >&2; exit 2 ;;
  esac
done

find_sdk() {
  local candidate
  for candidate in "${ANDROID_HOME:-}" "${ANDROID_SDK_ROOT:-}" "$HOME/Library/Android/sdk" "$HOME/.android/sdk"; do
    if [[ -n "$candidate" && -f "$candidate/emulator/lib/emulator_controller.proto" ]]; then
      echo "$candidate"
      return 0
    fi
  done
  return 1
}

if (( update_proto )); then
  sdk="$(find_sdk)" || { echo "error: no Android SDK with emulator/lib/emulator_controller.proto found" >&2; exit 1; }
  cp "$sdk/emulator/lib/emulator_controller.proto" "$PROTO"
  echo "Updated proto from $sdk"
fi

command -v protoc >/dev/null || { echo "error: protoc not found (brew install protobuf)" >&2; exit 1; }
command -v brew >/dev/null || { echo "error: brew not found; needed for protobuf's include directory" >&2; exit 1; }
[[ -f "$PROTO" ]] || { echo "error: missing $PROTO (run with --update-proto)" >&2; exit 1; }

swift build --package-path "$PKG" -c release --product protoc-gen-swift
swift build --package-path "$PKG" -c release --product protoc-gen-grpc-swift-2
BIN="$(swift build --package-path "$PKG" -c release --show-bin-path)"

target="$OUT"
if (( check )); then
  target="$(mktemp -d)"
  trap 'rm -rf "$target"' EXIT
else
  mkdir -p "$OUT"
  rm -f "$OUT"/*.swift
fi

protoc \
  --proto_path="$PROTO_DIR" \
  --proto_path="$(brew --prefix)/include" \
  --plugin=protoc-gen-swift="$BIN/protoc-gen-swift" \
  --plugin=protoc-gen-grpc-swift-2="$BIN/protoc-gen-grpc-swift-2" \
  --swift_out="$target" \
  --swift_opt=Visibility=Internal \
  --grpc-swift-2_out="$target" \
  --grpc-swift-2_opt=Visibility=Internal,Server=false,Client=true \
  "$PROTO"

resolved_version() {
  awk -v id="$1" '
    $0 ~ "\"identity\" : \"" id "\"" { found = 1 }
    found && /"version"/ { gsub(/[",]/, ""); print $3; exit }
  ' "$PKG/Package.resolved"
}

revision="unknown"
if sdk="$(find_sdk)" && [[ -f "$sdk/emulator/source.properties" ]]; then
  revision="$(sed -n 's/^Pkg.Revision=//p' "$sdk/emulator/source.properties")"
fi

cat > "$target/GENERATED_FROM.txt" <<INFO
Generated by scripts/android/generate-emulator-grpc.sh. Do not edit.
proto: emulator_controller.proto
proto sha256: $(shasum -a 256 "$PROTO" | awk '{print $1}')
emulator Pkg.Revision (local SDK at generation time): $revision
grpc-swift-protobuf: $(resolved_version grpc-swift-protobuf)
swift-protobuf: $(resolved_version swift-protobuf)
INFO

if (( check )); then
  diff -r "$target" "$OUT" && echo "Generated code is up to date."
else
  echo "Wrote $OUT"
fi
